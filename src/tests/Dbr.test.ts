/**
 * decode an array filled with numbers, this array is the full message from CA server
 */
const decodeBuffer = (bufferArray: number[]) => {
    const buffer = Buffer.from(bufferArray);
    // payload data info object
    const payloadData = Channel.extractDbrPayloadFromReadBuffer(buffer);
    const dbrBuffer = payloadData["dbrBuffer"];
    const dbrType = payloadData["dbrType"];
    const valueCount = payloadData["valueCount"];
    // Dbr object
    const dbr = new Dbr(Channel_DBR_TYPES.DBR_DOUBLE);
    dbr.decodeBuffer(dbrBuffer, dbrType, valueCount);
    const meta = dbr.getMeta();
    const value = dbr.getValue();
    return [value, dbrType, valueCount, meta];
}

