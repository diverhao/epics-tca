export enum ECA_SEVERITIES {
	CA_K_INFO = 3,
	CA_K_ERROR = 2,
	CA_K_SUCCESS = 1,
	CA_K_WARNING = 0,
	CA_K_SEVERE = 4,
	CA_K_FATAL = 6,
}

export class ECA {
	static encode = (severity: ECA_SEVERITIES, id: number): number => {
		return ((id << 3) & 0xfff8) | (severity & 0x7);
	};

	static decode = (code: number): {name: string, value: string, severity: string, id: number } => {
		const id = (code & 0xfff8) >> 3;
		const severity = code & 0x7;
        const name = ECA_VALUES[code];
        return {
            name: name,
            value: "0x" + code.toString(16),
            severity: ECA_SEVERITIES[severity],
            id: id,
        }
	};
}

